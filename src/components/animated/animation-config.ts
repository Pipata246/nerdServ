import type { Transition } from "framer-motion";

/**
 * Единые параметры для всех reveal-анимаций появления.
 * Одинаковая длительность, плавность и момент срабатывания
 * гарантируют, что элементы выкатываются одинаково и в нужный момент.
 *
 * - once: true — анимация срабатывает один раз при попадании в зону видимости
 *   и не переигрывается при прокрутке назад (убирает "хаос").
 * - amount: 0.2 — срабатывает, когда 20% элемента в зоне видимости.
 * - duration: 0.5 — умеренно быстро, не "слишком долго".
 * - ease — сглаженный cubic-bezier (easeOutQuart-подобный) для плавного выката.
 */
export const REVEAL_VIEWPORT = { once: true, amount: 0.2 } as const;

export const REVEAL_TRANSITION: Transition = {
  duration: 0.5,
  ease: [0.25, 0.1, 0.25, 1],
};
